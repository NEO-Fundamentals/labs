#!/usr/bin/env python3
# Translate /etc/neo/inspect.rules (the lab's small policy language) into
# Suricata rules at /etc/suricata/rules/neo.rules, then ask Suricata to reload
# if it is running. One rule per line:
#   mode ids | mode ips
#   block host <name>     HTTP Host header
#   block sni <name>      TLS server name
#   block content <text>  payload signature
#   alert app ssh         log SSH, never drop
import os, sys, time, subprocess

SRC = os.environ.get("NEO_POLICY", "/etc/neo/inspect.rules")
DST = os.environ.get("NEO_SURICATA_RULES", "/etc/suricata/rules/neo.rules")
MODE_FILE = "/run/neo-policy-mode"


def translate(text):
    mode = "ids"
    sid = 1000001
    out = []
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split(None, 2)
        if parts[0] == "mode" and len(parts) >= 2:
            if parts[1] in ("ids", "ips"):
                mode = parts[1]
            continue
        action = "alert" if mode == "ids" else "drop"
        if line.startswith("block host ") and len(parts) >= 3:
            name = parts[2]
            out.append(
                f'{action} http any any -> any any (msg:"block host {name}"; '
                f'http.host; content:"{name}"; sid:{sid}; rev:1;)'
            )
        elif line.startswith("block sni ") and len(parts) >= 3:
            name = parts[2]
            out.append(
                f'{action} tls any any -> any any (msg:"block sni {name}"; '
                f'tls.sni; content:"{name}"; sid:{sid}; rev:1;)'
            )
        elif line.startswith("block content ") and len(parts) >= 3:
            textv = parts[2]
            out.append(
                f'{action} ip any any -> any any (msg:"block content {textv}"; '
                f'content:"{textv}"; sid:{sid}; rev:1;)'
            )
        elif line == "alert app ssh":
            out.append(
                f'alert ssh any any -> any any (msg:"alert app ssh"; sid:{sid}; rev:1;)'
            )
        else:
            sys.stderr.write(f"unknown policy line: {raw}\n")
            continue
        sid += 1
    header = (
        f"# generated from {SRC}; mode {mode}. Do not edit this file by hand.\n"
    )
    return mode, header + ("\n".join(out) + ("\n" if out else ""))


def write_and_reload():
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    src = open(SRC, encoding="utf-8").read() if os.path.exists(SRC) else "mode ids\n"
    mode, rules = translate(src)
    open(MODE_FILE, "w", encoding="utf-8").write(mode + "\n")
    open(DST, "w", encoding="utf-8").write(rules)
    sock = "/var/run/suricata-command.socket"
    if os.path.exists(sock):
        r = subprocess.run(
            ["suricatasc", "-c", "reload-rules"],
            capture_output=True,
            text=True,
        )
        if r.returncode != 0:
            # Suricata may still be starting or stopping; the next watch tick retries.
            sys.stderr.write((r.stdout or "") + (r.stderr or ""))
    return True


def watch():
    last = None
    while True:
        try:
            st = os.stat(SRC) if os.path.exists(SRC) else None
            key = (st.st_mtime, st.st_size) if st else None
        except OSError:
            key = None
        if key != last:
            write_and_reload()
            last = key
        time.sleep(0.5)


if __name__ == "__main__":
    if "--watch" in sys.argv:
        watch()
    else:
        sys.exit(0 if write_and_reload() else 1)
